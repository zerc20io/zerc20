#!/usr/bin/env node
// Dev/testnet artifacts for the four circuits: a fresh randomized setup per circuit, its Solidity
// verifier placed in contracts/, and its keys uploaded to S3.
//
//   node scripts/artifacts.mjs setup  [joinsplit rageexit root merge]   (default: all four)
//   ZKP_ARTIFACTS_S3=s3://bucket/prefix node scripts/artifacts.mjs upload [circuits...]
//
// setup writes zkp/artifacts/<circuit>/ with the keys and a setup.json {circuit, id, files: {name:
// {size, sha256}}}. Circom circuits share a locally generated random ptau cached in
// zkp/artifacts/ptau/. upload copies the files in setup.json to <S3>/<circuit>/<id>/, the circom wasm and
// zkey Brotli-encoded, then setup.json to <S3>/<circuit>/latest.json. The setup id is also written into
// each generated contract.
//
// Every key comes from one process with random entropy: TESTNET ONLY, never for mainnet. The exports below also write
// the trusted setup ceremony's keys into the same layout.

import { execFileSync } from 'node:child_process';
import { createHash, randomBytes } from 'node:crypto';
import {
  createReadStream,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { brotliCompressSync, constants } from 'node:zlib';
import * as snarkjs from 'snarkjs';

// snarkjs as this module loads it, for a script that works on the same zkeys: a second copy loaded beside it would
// share its curve workers and none of its classes
export { snarkjs };
export const ROOT = path.resolve(import.meta.dirname, '../..');
export const ZKP = path.join(ROOT, 'zkp');
export const OUT = path.join(ZKP, 'artifacts');
const PTAU_DIR = path.join(OUT, 'ptau');
const CONTRACTS = path.join(ROOT, 'contracts');
const GENERATED = path.join(CONTRACTS, 'src/verifiers/generated');
const INTERFACES = '../../interfaces';

export const CIRCUITS = {
  joinsplit: { kind: 'circom', title: 'JoinSplit' },
  rageexit: { kind: 'circom', title: 'RageExit' },
  root: { kind: 'nova', title: 'Root', iface: 'IRootDeciderVerifier' },
  merge: { kind: 'nova', title: 'Merge', iface: 'IMergeDeciderVerifier' },
};

export const KEY_FILES = {
  circom: (c) => [`${c}.wasm`, `${c}.zkey`, `${c}_vk.json`],
  nova: (c) => [`${c}_ivc_key.bin`, `${c}_decider_pk.bin`, `${c}_decider_vk.bin`],
};

// The zkp/test-vectors burn address (sk 42, salt 2279, chain 1), deposited at ledger index 0 in
// contracts/test/Core.t.sol.
const RAGE_EXIT_INPUT = {
  chain_id: '1',
  commitment_index: '0',
  burn_address: BigInt('0x96aC69527F3b2c96fad588F3E1818c2CAC995D51').toString(),
  private_key: '42',
  auth_key_hash: '17681195958231059701268167412646292838960155012585722262908631477582403623144',
  burn_salt: '2279',
};

export const logger = { debug() {}, info: console.log, warn: console.warn, error: console.error };
const entropy = () => randomBytes(32).toString('hex');
export const run = (cmd, args, cwd = ZKP) => execFileSync(cmd, args, { cwd, stdio: 'inherit' });
export const writeJson = (file, value) =>
  writeFileSync(file, `${JSON.stringify(value, (_, v) => (typeof v === 'bigint' ? v.toString() : v), 2)}\n`);

/** `src.replace(re, to)` that fails loudly when a template no longer matches. */
function sub(src, re, to) {
  if (!re.test(src)) throw new Error(`generated source no longer matches ${re}`);
  return src.replace(re, to);
}

// A deployment reads the setup id back from `(setup <id>)`, and refuses a TESTNET ONLY verifier outside testnet.
function header(license, imports, notice, id, testnet) {
  return `// SPDX-License-Identifier: ${license}
pragma solidity 0.8.37;
${imports}
/// @notice ${notice}
/// @dev Generated by zkp/scripts/artifacts.mjs (setup ${id}); do not edit manually.
${
  testnet
    ? '/// @dev TESTNET ONLY - single-operator randomized setup; not for mainnet.'
    : '/// @dev Keys from the multi-party trusted setup ceremony.'
}
`;
}

/** Smallest cached ptau of at least `power`, generated with random entropy when missing. */
async function ptauFor(power) {
  mkdirSync(PTAU_DIR, { recursive: true });
  const cached = readdirSync(PTAU_DIR)
    .map((f) => Number(f.match(/^pot(\d+)\.ptau$/)?.[1]))
    .filter((p) => p >= power)
    .sort((a, b) => a - b)[0];
  if (cached) return path.join(PTAU_DIR, `pot${cached}.ptau`);

  const out = path.join(PTAU_DIR, `pot${power}.ptau`);
  const [fresh, contributed, prepared] = ['.0', '.1', '.2'].map((s) => out + s);
  const curve = await snarkjs.curves.getCurveFromName('bn128');
  await snarkjs.powersOfTau.newAccumulator(curve, power, fresh, logger);
  await snarkjs.powersOfTau.contribute(fresh, contributed, 'dev', entropy(), logger);
  await snarkjs.powersOfTau.preparePhase2(contributed, prepared, logger);
  renameSync(prepared, out); // only a finished ptau gets the cached name
  rmSync(fresh);
  rmSync(contributed);
  return out;
}

/** Compiles circuit `c` into `dir`, leaving `<c>.r1cs` and `<c>.wasm`; returns the r1cs path. */
export function compileCircom(c, dir) {
  run('circom', [`circom/main/${c}.circom`, '--r1cs', '--wasm', '--O2', '-o', dir]);
  renameSync(path.join(dir, `${c}_js`, `${c}.wasm`), path.join(dir, `${c}.wasm`));
  rmSync(path.join(dir, `${c}_js`), { recursive: true });
  return path.join(dir, `${c}.r1cs`);
}

/** The power of two a ptau needs for the circom r1cs at `r1cs`. */
export async function circomPower(r1cs) {
  const info = await snarkjs.r1cs.info(r1cs);
  return (info.nConstraints + info.nPubInputs + info.nOutputs).toString(2).length;
}

/** The zkey of a new phase 2 for `r1cs` over `ptau`. The CLI ignores newZKey's -1 and exits 0 with a broken zkey. */
export async function newZKey(c, r1cs, ptau, zkey) {
  if ((await snarkjs.zKey.newZKey(r1cs, ptau, zkey, logger)) === -1) throw new Error(`${c}: groth16 setup failed`);
}

async function setupCircom(c, spec, dir, id) {
  const r1cs = compileCircom(c, dir);
  const ptau = await ptauFor(await circomPower(r1cs));
  const zkey0 = path.join(dir, `${c}_0.zkey`);
  await newZKey(c, r1cs, ptau, zkey0);
  // Without a contribution delta stays 1 and proofs are forgeable.
  await snarkjs.zKey.contribute(zkey0, path.join(dir, `${c}.zkey`), 'dev', entropy(), logger);
  rmSync(zkey0);
  return exportCircom(c, spec, dir, id, true);
}

/** From `dir`'s `<c>.wasm` and `<c>.zkey`: `<c>_vk.json`, the Solidity verifier and, for rageexit, the test fixture. */
export async function exportCircom(c, { title }, dir, id, testnet) {
  const wasm = path.join(dir, `${c}.wasm`);
  const zkey = path.join(dir, `${c}.zkey`);
  writeJson(path.join(dir, `${c}_vk.json`), await snarkjs.zKey.exportVerificationKey(zkey));

  const template = readFileSync(path.join(ZKP, 'node_modules/snarkjs/templates/verifier_groth16.sol.ejs'), 'utf8');
  const sol = await snarkjs.zKey.exportSolidityVerifier(zkey, { groth16: template }, logger);
  const iface = `I${title}Verifier`;
  const written = [path.join(GENERATED, `${title}Groth16Verifier.sol`)];
  writeFileSync(
    written[0],
    sub(
      sol,
      /^[\s\S]*?contract Groth16Verifier \{/,
      `${header(
        'GPL-3.0',
        `\nimport {${iface}} from "${INTERFACES}/IPrivateProofVerifier.sol";\n`,
        `snarkjs Groth16 verifier for zkp/circom/main/${c}.circom.`,
        id,
        testnet,
      )}contract ${title}Groth16Verifier is ${iface} {`,
    ),
  );

  if (c === 'rageexit') {
    const { proof, publicSignals } = await snarkjs.groth16.fullProve(RAGE_EXIT_INPUT, wasm, zkey);
    const [a, b, pc] = [proof.pi_a, proof.pi_b, proof.pi_c];
    written.push(path.join(CONTRACTS, 'test/RageExitFixture.sol'));
    writeFileSync(
      written[1],
      `// SPDX-License-Identifier: MIT
pragma solidity 0.8.37;

import {Groth16Proof} from "../src/interfaces/IPrivateProofVerifier.sol";

// Generated by zkp/scripts/artifacts.mjs (setup ${id}) with the zkey behind RageExitGroth16Verifier:
// a RageExit proof for the zkp/test-vectors burn address (sk 42, salt 2279, chain 1) at ledger index 0.

uint256 constant BURN_NULLIFIER = ${publicSignals[0]};

function rageExitProof() pure returns (Groth16Proof memory) {
    return Groth16Proof({
        pA: [uint256(${a[0]}), ${a[1]}],
        pB: [[uint256(${b[0][1]}), ${b[0][0]}], [uint256(${b[1][1]}), ${b[1][0]}]],
        pC: [uint256(${pc[0]}), ${pc[1]}]
    });
}
`,
    );
  }
  return written;
}

async function setupNova(c, spec, dir, id) {
  run('cargo', ['run', '--release', '--locked', '-p', 'zerc20-zkp', '--bin', 'params_gen', '--', c, dir], ROOT);
  return exportNova(c, spec, dir, id, true);
}

/** `<Title>NovaVerifier.sol` from the two contracts sonobe renders into `dir`. */
export function exportNova(c, { title, iface }, dir, id, testnet) {
  // sonobe renders two files with fixed contract names and a non-relative import; flatten them into
  // one file with per-circuit names so root and merge can live side by side.
  const lego = readFileSync(path.join(dir, 'LegoGroth16Verifier.sol'), 'utf8');
  const decider = readFileSync(path.join(dir, `${title}DeciderVerifier.sol`), 'utf8');
  const written = [path.join(GENERATED, `${title}NovaVerifier.sol`)];
  writeFileSync(
    written[0],
    header(
      'MIT',
      `\nimport {${iface}} from "${INTERFACES}/INovaDeciderVerifier.sol";\n`,
      `Sonobe Nova decider verifier for the ${c} step circuit.`,
      id,
      testnet,
    ) +
      sub(lego, /^[\s\S]*?contract LegoGroth16Verifier \{/, `contract ${title}LegoGroth16Verifier {`) +
      '\n' +
      sub(
        sub(decider, /^[\s\S]*?import "LegoGroth16Verifier.sol";\n/, ''),
        /contract DeciderVerifier is LegoGroth16Verifier \{/,
        `contract ${title}DeciderVerifier is ${title}LegoGroth16Verifier, ${iface} {`,
      ),
  );
  return written;
}

export async function identity(file) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(file)) hash.update(chunk);
  return { size: statSync(file).size, sha256: hash.digest('hex') };
}

/** `<UTC time>-<git describe>`, which never contains the `)` that ends `(setup <id>)`. */
export function setupId() {
  const describe = execFileSync('git', ['describe', '--always', '--dirty'], { cwd: ROOT }).toString().trim();
  return `${new Date().toISOString().replace(/[-:]|\.\d+/g, '')}-${describe}`;
}

/** An empty `zkp/artifacts/<c>/`, so a failed run never leaves old keys next to a fresh setup.json. */
export function freshDir(c) {
  const dir = path.join(OUT, c);
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  return dir;
}

/** `setup.json` for the keys in `dir`, with whatever else `extra` names about where they came from. */
export async function writeSetup(c, dir, id, extra = {}) {
  const files = {};
  for (const name of KEY_FILES[CIRCUITS[c].kind](c)) files[name] = await identity(path.join(dir, name));
  writeJson(path.join(dir, 'setup.json'), { circuit: c, id, files, ...extra });
}

export function formatContracts(written) {
  run('forge', ['fmt', ...written], CONTRACTS);
  console.log(`==> wrote\n${written.map((f) => `  ${path.relative(ROOT, f)}`).join('\n')}`);
}

async function setup(circuits) {
  const id = setupId();
  const written = [];
  for (const c of circuits) {
    const spec = CIRCUITS[c];
    const dir = freshDir(c);
    console.log(`==> ${c}: setup ${id}`);
    written.push(...(await (spec.kind === 'circom' ? setupCircom : setupNova)(c, spec, dir, id)));
    await writeSetup(c, dir, id);
  }
  formatContracts(written);
}

// What a wallet fetches before its first proof, by its Content-Type. Stored Brotli-encoded: CloudFront compresses
// nothing past 10 MB, and Brotli halves a zkey. Browsers and Node's fetch decode it, so what they check against
// setup.json's SHA-256 is the file itself.
const ENCODED = { '.wasm': 'application/wasm', '.zkey': 'application/octet-stream' };

// A setup's files never change under its id, so caches keep them; latest.json moves to each new setup.
const IMMUTABLE = ['--cache-control', 'public, max-age=31536000, immutable'];

function upload(circuits) {
  const s3 = process.env.ZKP_ARTIFACTS_S3?.replace(/\/+$/, '');
  if (!s3?.startsWith('s3://')) throw new Error('set ZKP_ARTIFACTS_S3=s3://bucket/prefix');
  const tmp = mkdtempSync(path.join(tmpdir(), 'artifacts-'));
  try {
    for (const c of circuits) {
      const dir = path.join(OUT, c);
      const { id, files } = JSON.parse(readFileSync(path.join(dir, 'setup.json'), 'utf8'));
      for (const name of [...Object.keys(files), 'setup.json']) {
        const file = path.join(dir, name);
        const to = `${s3}/${c}/${id}/${name}`;
        const type = ENCODED[path.extname(name)];
        if (!type) {
          run('aws', ['s3', 'cp', file, to, ...IMMUTABLE]);
          continue;
        }
        const bytes = readFileSync(file);
        const br = path.join(tmp, name);
        writeFileSync(
          br,
          brotliCompressSync(bytes, {
            params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: bytes.length },
          }),
        );
        run('aws', ['s3', 'cp', br, to, '--content-encoding', 'br', '--content-type', type, ...IMMUTABLE]);
      }
      // Last, so latest.json never points at a partial upload.
      run('aws', ['s3', 'cp', path.join(dir, 'setup.json'), `${s3}/${c}/latest.json`, '--cache-control', 'no-cache']);
    }
  } finally {
    rmSync(tmp, { recursive: true });
  }
}

if (import.meta.main) {
  const [command, ...names] = process.argv.slice(2);
  const circuits = names.length ? names : Object.keys(CIRCUITS);
  const unknown = circuits.filter((c) => !CIRCUITS[c]);
  if (!['setup', 'upload'].includes(command) || unknown.length) {
    console.error(`usage: artifacts.mjs <setup|upload> [${Object.keys(CIRCUITS).join('|')} ...]`);
    process.exit(2);
  }
  await (command === 'setup' ? setup(circuits) : upload(circuits));
  // snarkjs keeps curve worker threads alive.
  process.exit(0);
}
