//! (De)serialization of the Nova pipeline keys, generic over the step
//! circuit's state type `S`, and the files a setup writes them to.
//!
//! Sonobe does not derive `CanonicalSerialize`/`CanonicalDeserialize` for the
//! LegoGroth16 key types or the CycleFold IVC `Key` wrapper, so this module
//! persists them field by field (every field is `pub` in sonobe). The field
//! order below must stay in sync with the sonobe struct definitions at the
//! revision pinned in `Cargo.lock`.
//!
//! Artifacts are stored UNCOMPRESSED: the decider prover key holds on the
//! order of 10^8 curve points, and per-point decompression (a square root
//! each) turns loading into minutes of CPU work, while the uncompressed form
//! is IO-bound.
//!
//! Every artifact additionally has two readers: the checked `read_*` variant
//! validates every deserialized group element (subgroup checks), and the
//! `read_*_trusted` variant skips validation. The trusted variants must ONLY
//! be used on artifacts the caller itself generated (e.g. a prover loading its
//! own `params_gen` output), never on downloaded or
//! otherwise untrusted data.

use std::{
    error::Error,
    fs::File,
    io::{BufWriter, Read, Write},
    path::Path,
};

use ark_bn254::{Bn254, Fr};
use ark_crypto_primitives::sponge::poseidon::PoseidonConfig;
use ark_serialize::{
    CanonicalDeserialize, CanonicalSerialize, Compress, SerializationError, Validate,
};
use askama::Template;
use sonobe_ivc::compilers::cyclefold::{
    Key,
    evm_verifier::{CycleFoldBasedIVCDeciderVerifierTemplate, FCircuitEVMExt},
};
use sonobe_snarks::cp::legogroth16::{self as lego, evm_verifier::LegoGroth16VerifierTemplate};

use crate::ivc::{DeciderProverKey, DeciderVerifierKey, IvcKey, PrimaryNova};

type LegoProverKey = lego::ProverKey<Bn254>;
type LegoVerifierKey = lego::VerifierKey<Bn254>;

fn read<T: CanonicalDeserialize>(
    r: &mut impl Read,
    validate: Validate,
) -> Result<T, SerializationError> {
    T::deserialize_with_mode(r, Compress::No, validate)
}

/// Serializes the IVC key (the prover and verifier key are the same `Key`
/// value for the CycleFold compiler, so only one copy is persisted).
pub fn write_ivc_key<S: CanonicalSerialize + Clone>(
    mut w: impl Write,
    key: &IvcKey<S>,
) -> Result<(), SerializationError> {
    let Key(dk1, dk2, (hash_config, pp_hash, reference_state)) = key;
    dk1.serialize_uncompressed(&mut w)?;
    dk2.serialize_uncompressed(&mut w)?;
    hash_config.serialize_uncompressed(&mut w)?;
    pp_hash.serialize_uncompressed(&mut w)?;
    reference_state.serialize_uncompressed(&mut w)?;
    Ok(())
}

fn read_ivc_key_with<S: CanonicalDeserialize + Clone>(
    mut r: impl Read,
    validate: Validate,
) -> Result<IvcKey<S>, SerializationError> {
    let dk1 = read(&mut r, validate)?;
    let dk2 = read(&mut r, validate)?;
    let hash_config: PoseidonConfig<Fr> = read(&mut r, validate)?;
    let pp_hash: Fr = read(&mut r, validate)?;
    let reference_state: S = read(&mut r, validate)?;
    Ok(Key(dk1, dk2, (hash_config, pp_hash, reference_state)))
}

pub fn read_ivc_key<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<IvcKey<S>, SerializationError> {
    read_ivc_key_with(r, Validate::Yes)
}

/// Unvalidated read — only for artifacts generated by the caller itself.
pub fn read_ivc_key_trusted<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<IvcKey<S>, SerializationError> {
    read_ivc_key_with(r, Validate::No)
}

fn write_committed_indices(
    mut w: impl Write,
    indices: &sonobe_primitives::circuits::cache::UsizeSet,
) -> Result<(), SerializationError> {
    let mut sorted: Vec<u64> = indices.iter().map(|&i| i as u64).collect();
    sorted.sort_unstable();
    sorted.serialize_uncompressed(&mut w)
}

fn read_committed_indices(
    mut r: impl Read,
    validate: Validate,
) -> Result<sonobe_primitives::circuits::cache::UsizeSet, SerializationError> {
    let sorted: Vec<u64> = read(&mut r, validate)?;
    Ok(sorted.into_iter().map(|i| i as usize).collect())
}

fn write_lego_prover_key(mut w: impl Write, pk: &LegoProverKey) -> Result<(), SerializationError> {
    pk.r1cs.serialize_uncompressed(&mut w)?;
    write_committed_indices(&mut w, &pk.committed_variable_indices)?;
    let cc = &pk.cc_pk;
    cc.alpha_g1.serialize_uncompressed(&mut w)?;
    cc.beta_g1.serialize_uncompressed(&mut w)?;
    cc.beta_g2.serialize_uncompressed(&mut w)?;
    cc.delta_g1.serialize_uncompressed(&mut w)?;
    cc.delta_g2.serialize_uncompressed(&mut w)?;
    cc.eta_delta_inv_g1.serialize_uncompressed(&mut w)?;
    cc.eta_gamma_inv_g1.serialize_uncompressed(&mut w)?;
    cc.a_query.serialize_uncompressed(&mut w)?;
    cc.b_g1_query.serialize_uncompressed(&mut w)?;
    cc.b_g2_query.serialize_uncompressed(&mut w)?;
    cc.h_query.serialize_uncompressed(&mut w)?;
    cc.l_query.serialize_uncompressed(&mut w)?;
    cc.gamma_abc_g1_cm.serialize_uncompressed(&mut w)?;
    pk.link_ek.serialize_uncompressed(&mut w)?;
    Ok(())
}

fn read_lego_prover_key(
    mut r: impl Read,
    validate: Validate,
) -> Result<LegoProverKey, SerializationError> {
    Ok(LegoProverKey {
        r1cs: read(&mut r, validate)?,
        committed_variable_indices: read_committed_indices(&mut r, validate)?,
        cc_pk: lego::CCGroth16ProverKey {
            alpha_g1: read(&mut r, validate)?,
            beta_g1: read(&mut r, validate)?,
            beta_g2: read(&mut r, validate)?,
            delta_g1: read(&mut r, validate)?,
            delta_g2: read(&mut r, validate)?,
            eta_delta_inv_g1: read(&mut r, validate)?,
            eta_gamma_inv_g1: read(&mut r, validate)?,
            a_query: read(&mut r, validate)?,
            b_g1_query: read(&mut r, validate)?,
            b_g2_query: read(&mut r, validate)?,
            h_query: read(&mut r, validate)?,
            l_query: read(&mut r, validate)?,
            gamma_abc_g1_cm: read(&mut r, validate)?,
        },
        link_ek: read(&mut r, validate)?,
    })
}

fn write_lego_verifier_key(
    mut w: impl Write,
    vk: &LegoVerifierKey,
) -> Result<(), SerializationError> {
    let cc = &vk.cc_vk;
    cc.alpha_g1.serialize_uncompressed(&mut w)?;
    cc.beta_g2_neg.serialize_uncompressed(&mut w)?;
    cc.gamma_g2_neg.serialize_uncompressed(&mut w)?;
    cc.delta_g2_neg.serialize_uncompressed(&mut w)?;
    cc.alpha_g1_beta_g2.serialize_uncompressed(&mut w)?;
    cc.gamma_g2_neg_pc.serialize_uncompressed(&mut w)?;
    cc.delta_g2_neg_pc.serialize_uncompressed(&mut w)?;
    cc.gamma_abc_g1_pub.serialize_uncompressed(&mut w)?;
    vk.link_vk.serialize_uncompressed(&mut w)?;
    Ok(())
}

fn read_lego_verifier_key(
    mut r: impl Read,
    validate: Validate,
) -> Result<LegoVerifierKey, SerializationError> {
    Ok(LegoVerifierKey {
        cc_vk: lego::CCGroth16VerifierKey {
            alpha_g1: read(&mut r, validate)?,
            beta_g2_neg: read(&mut r, validate)?,
            gamma_g2_neg: read(&mut r, validate)?,
            delta_g2_neg: read(&mut r, validate)?,
            alpha_g1_beta_g2: read(&mut r, validate)?,
            gamma_g2_neg_pc: read(&mut r, validate)?,
            delta_g2_neg_pc: read(&mut r, validate)?,
            gamma_abc_g1_pub: read(&mut r, validate)?,
        },
        link_vk: read(&mut r, validate)?,
    })
}

/// Serializes the decider prover key `(LegoGroth16 pk, IVC vk)`.
pub fn write_decider_prover_key<S: CanonicalSerialize + Clone>(
    mut w: impl Write,
    (pk, ivc_vk): &DeciderProverKey<S>,
) -> Result<(), SerializationError> {
    write_lego_prover_key(&mut w, pk)?;
    write_ivc_key(&mut w, ivc_vk)
}

fn read_decider_prover_key_with<S: CanonicalDeserialize + Clone>(
    mut r: impl Read,
    validate: Validate,
) -> Result<DeciderProverKey<S>, SerializationError> {
    let pk = read_lego_prover_key(&mut r, validate)?;
    let ivc_vk = read_ivc_key_with(&mut r, validate)?;
    Ok((pk, ivc_vk))
}

pub fn read_decider_prover_key<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<DeciderProverKey<S>, SerializationError> {
    read_decider_prover_key_with(r, Validate::Yes)
}

/// Unvalidated read — only for artifacts generated by the caller itself. The
/// decider prover key holds millions of curve points; skipping the per-point
/// subgroup checks cuts its load time by an order of magnitude.
pub fn read_decider_prover_key_trusted<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<DeciderProverKey<S>, SerializationError> {
    read_decider_prover_key_with(r, Validate::No)
}

/// Serializes the decider verifier key
/// `(LegoGroth16 vk, folding vk = (), transcript config, pp hash, reference state)`.
pub fn write_decider_verifier_key<S: CanonicalSerialize + Clone>(
    mut w: impl Write,
    (vk, (), hash_config, pp_hash, reference_state): &DeciderVerifierKey<S>,
) -> Result<(), SerializationError> {
    write_lego_verifier_key(&mut w, vk)?;
    hash_config.serialize_uncompressed(&mut w)?;
    pp_hash.serialize_uncompressed(&mut w)?;
    reference_state.serialize_uncompressed(&mut w)?;
    Ok(())
}

fn read_decider_verifier_key_with<S: CanonicalDeserialize + Clone>(
    mut r: impl Read,
    validate: Validate,
) -> Result<DeciderVerifierKey<S>, SerializationError> {
    let vk = read_lego_verifier_key(&mut r, validate)?;
    let hash_config: PoseidonConfig<Fr> = read(&mut r, validate)?;
    let pp_hash: Fr = read(&mut r, validate)?;
    let reference_state: S = read(&mut r, validate)?;
    Ok((vk, (), hash_config, pp_hash, reference_state))
}

pub fn read_decider_verifier_key<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<DeciderVerifierKey<S>, SerializationError> {
    read_decider_verifier_key_with(r, Validate::Yes)
}

/// Unvalidated read — only for artifacts generated by the caller itself.
pub fn read_decider_verifier_key_trusted<S: CanonicalDeserialize + Clone>(
    r: impl Read,
) -> Result<DeciderVerifierKey<S>, SerializationError> {
    read_decider_verifier_key_with(r, Validate::No)
}

fn write_file(
    path: &Path,
    write: impl FnOnce(&mut BufWriter<File>) -> Result<(), SerializationError>,
) -> Result<(), Box<dyn Error>> {
    let mut writer = BufWriter::new(File::create(path)?);
    write(&mut writer)?;
    writer.flush()?;
    Ok(())
}

/// Writes one step circuit's keys and EVM verifiers into `dir`:
/// `<name>_ivc_key.bin`, `<name>_decider_pk.bin`, `<name>_decider_vk.bin`,
/// `LegoGroth16Verifier.sol` and `<title>DeciderVerifier.sol`. Sonobe always
/// names the rendered contracts `LegoGroth16Verifier` and `DeciderVerifier`,
/// so each circuit gets a directory of its own.
pub fn write_nova_artifacts<FC: FCircuitEVMExt<Field = Fr>>(
    dir: &Path,
    name: &str,
    title: &str,
    pk: &DeciderProverKey<FC::State>,
    vk: &DeciderVerifierKey<FC::State>,
) -> Result<(), Box<dyn Error>>
where
    FC::State: CanonicalSerialize,
{
    std::fs::create_dir_all(dir)?;
    write_file(&dir.join(format!("{name}_ivc_key.bin")), |w| {
        write_ivc_key(w, &pk.1)
    })?;
    write_file(&dir.join(format!("{name}_decider_pk.bin")), |w| {
        write_decider_prover_key(w, pk)
    })?;
    write_file(&dir.join(format!("{name}_decider_vk.bin")), |w| {
        write_decider_verifier_key(w, vk)
    })?;
    std::fs::write(
        dir.join("LegoGroth16Verifier.sol"),
        LegoGroth16VerifierTemplate { vk: &vk.0 }.render()?,
    )?;
    std::fs::write(
        dir.join(format!("{title}DeciderVerifier.sol")),
        CycleFoldBasedIVCDeciderVerifierTemplate::<PrimaryNova, FC>::new(&vk.0, &vk.4).render()?,
    )?;
    Ok(())
}
